# %% [markdown]
# ## 3. β(E) for all three LEM versions, with the exact two-track curve
#
# Survival slope-matches the **unsaturated** $\alpha_z$ and then rescales by
# $(\alpha_D/\alpha_z)^2$. pyRadBio's default `slope_matching` applies
# $(s_\mathrm{max}-\alpha_I)/(2D_t)$ to the **saturated** $\alpha_I$. At high LET
# $\alpha_D \ll \alpha_z$, so the rescale pulls Survival's β down while ours
# stays up — the whole 41% oxygen gap. `beta_model="rapid_lem"` *is* Survival's
# formula, which is why it recovers 1–3% agreement.
#
# Neither is LEM-native. `beta_model="scholz1997_two_track"` is: it computes β
# from the actual **non-additive dose overlap of track pairs** (Scholz et al.
# 1997), with no slope-matching heuristic anywhere — the arbiter for which of the
# two approximations is closer to the model's own answer, and not obliged to
# agree with either.
#
# **All three are available for LEM I, II and III.** They live on `LEMBase`,
# because all three need only that the lethal-event density be a *pointwise*
# function of the local dose — which LEM II/III satisfy, since eq. 10 scales the
# dose by `η(D)` and `η` depends on nothing but `D`. LEM II/III override the
# photon response in **both** its scalar and array forms (overriding only the
# scalar would hand the un-enhanced LEM I response to `two_track` under a LEM
# II/III label). **LEM IV is excluded by construction**: its effect is a function
# of a *global* DSB-pattern statistic (the cluster index), so there is no `h(d)`
# to difference and `LEM4.scholz1997_two_track_beta` raises;
# `beta_model="rapid_lem"` is available there, through LEM IV's own `N_1`.
#
# Cost: ~1-5 s per point for LEM I, but **tens of seconds** for LEM II/III and
# strongly energy-dependent (~5 s at 100 MeV/u against ~40 s at 150-200 MeV/u for
# the same ion: the far-field dose of a high-energy track underflows toward
# denormals, which are microcoded and far slower). So LEM I's runs by default and
# LEM II/III's is opt-in (`RUN_TWO_TRACK_LEM23`). Below ~3 MeV/u for C/O the
# O(φ²) expansion goes slightly negative and is clamped to 0 with a warning — a
# floor, not a value, shown for continuity only.
#
# ### What the low-energy end of the heavy-ion panels shows
#
# In the 12C and 16O panels of **every** row, our `slope_matching` curve turns
# *upward* toward low energy while the Survival curves, `rapid_lem`, and
# `two_track` all go to zero:
#
# | 12C | α_I | slope_matching | rapid_lem | two_track | Survival |
# |---|---|---|---|---|---|
# | 1 MeV/u (LET 747) | 0.661 | **0.0557** | 0.0000 | 0.0000 | 0.0000 |
# | 3 MeV/u (LET 414) | 1.158 | **0.0474** | 0.0004 | 0.0000 | 0.0007 |
# | 10 MeV/u (LET 174) | 1.590 | 0.0402 | 0.0131 | 0.0034 | 0.0142 |
#
# That is a **structural artifact of slope matching**, not a tuning difference.
# `β = (s_max − α_I)/(2 D_t)` is *anti-correlated* with α_I, and the exact
# `cross_section` α_I is **not monotone in LET** — it peaks near 10 MeV/u and then
# *thins down* under overkill (0.661 at 1 MeV/u). Slope matching reads that
# thinning as "room left under `s_max`" and puts β back up, to 0.0557 ≈ 0.9 β_x,
# at a LET where the cell is being killed many times over per track and every
# other method says 0. So at high LET `two_track` < `rapid_lem` ≈ Survival ≪
# `slope_matching`: the LEM-native answer is the *lowest*, both approximations
# overshoot, and `slope_matching` overshoots qualitatively.

# %%
fig, axes = plt.subplots(3, 4, figsize=(17, 11), sharex=True)
beta_lems = {}
