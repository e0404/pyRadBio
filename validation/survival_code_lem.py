# So the spread is theirs, reproduced through a wholly separate (sampling) path:
# read the patched crosses as the fair line, not the LEM II/III squares.
MC_PAIRED = {m: _load(m, "MonteCarloPaired") for m in MODELS}
# The same sweep against a Survival build with `CellLine.cpp`'s exponentiated
# `logS_t2`/`logS_t3` patched out (§6a of the notes). LEM II/III only — LEM I's
# photon path never had the defect. A second reference dataset from a second
# binary; nothing here changes what our models compute.
PATCHED = {m: _load(m, "Russo2011Patched") for m in ("LEMII", "LEMIII")}

# A pyRadBio LEM on the HSG parameters, driven by Survival's own LET. LEM I runs on
# Survival's `r_max` (gamma = 0.062, not Scholz & Kraft 1996's 0.05): see
# `manganaro2018.survival_matched_lem` and section 1 below.
LEMS = {m: m18.survival_matched_lem(m, STOPPING) for m in MODELS}


def mc_curve(source: dict[str, rt.SurvivalLQTable | None], model: str, Z: int, A: int):
    """The MC curve for one (model, ion), or None if that point was never run."""
    table = source.get(model)
    if table is None:
        return None
    try:
        return table.curve(Z, A)
    except (KeyError, ValueError):
        return None


_CACHE = JsonPointCache(OUR_MC_CACHE)
_MISSING: list[str] = []


def our_mc(model: str, Z: int, A: int) -> dict[str, np.ndarray] | None:
    """pyRadBio's MC for one (model, ion) from the committed cache, or None.

    The points are those `scripts/lem_mc_vs_survival.py` generates
    (`manganaro2018.OUR_MC.energies`), looked up under the hash of everything that
    can change them (`manganaro2018.mc_cache_key`), so a stale entry is never read.
    """
    keys = ("let", "alpha", "alpha_sigma", "beta", "beta_sigma", "n_real")
    out: dict[str, list[float]] = {k: [] for k in keys}
    found: list[float] = []
    for e_u in m18.OUR_MC.energies(model, Z):
        entry = _CACHE.get(m18.mc_cache_key(model, Z, A, e_u, LEMS[model], STOPPING))
        if entry is None:
            _MISSING.append(f"{model}|Z{Z}|{e_u:g}")
            continue
        found.append(e_u)
        for k in keys:
            out[k].append(entry[k])
    if not found:
        return None
    return {"energies": np.array(found), **{k: np.array(v) for k, v in out.items()}}


OUR_MC = {(m, Z): our_mc(m, Z, A) for m in m18.OUR_MC.models() for Z, A, _, _ in IONS}
if _MISSING:
    print(
        f"{len(_MISSING)} pyRadBio MC points missing from {OUR_MC_CACHE.name} "
        f"(regenerate with scripts/lem_mc_vs_survival.py): {', '.join(_MISSING)}"
    )


def draw_our_mc(ax, model: str, Z: int, attr: str, *, x="energy") -> None:
    """Overlay pyRadBio's own Monte Carlo for this (model, ion)."""
    d = OUR_MC.get((model, Z))
    if d is None:
        return
    ax.errorbar(
        d["energies"] if x == "energy" else d["let"],
        d[attr],
        yerr=d[f"{attr}_sigma"],
        label="pyRadBio MC",
        **OUR_MC_STYLE,
    )


def grid_legend(ax, axes, **kw) -> None:
    """One legend naming every series in the grid, not just this panel's.

    No single panel carries the full set (LEM I has the 8000-cell MC pass that
    LEM II/III lack; LEM II/III have the patched-Survival curve LEM I lacks), so
    handles are collected across every axis and deduplicated by label, keeping
    the first of each.
    """
    seen: dict[str, object] = {}
    for one in np.ravel(np.asarray(axes, dtype=object)):
        for handle, label in zip(*one.get_legend_handles_labels(), strict=True):
            seen.setdefault(label, handle)
    ax.legend(list(seen.values()), list(seen), **kw)


def draw_mc(ax, model: str, Z: int, A: int, attr: str, *, x="energy") -> None:
    """Overlay both MC passes of `attr` ('alpha' or 'beta') where they exist."""
    for source, style, suffix in (
        (MC, MC_STYLE, ""),
        (MC_HIP, MC_HIP_STYLE, " (8000 cells)"),
        (MC_PAIRED, MC_PAIRED_STYLE, " (paired)"),
    ):
        c = mc_curve(source, model, Z, A)
        if c is None:
            continue
        energies = np.asarray(c.energies_MeV_u, dtype=float)
        xs = (
            energies
            if x == "energy"
            else np.array([STOPPING.let_keV_um(Ion(Z, A, float(e))) for e in energies])
        )
        ax.errorbar(
            xs,
            getattr(c, attr),
            yerr=getattr(c, f"{attr}_sigma"),
            label=f"Survival MC{suffix}",
            **style,
        )


