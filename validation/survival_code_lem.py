# %% [markdown]
# # pyRadBio vs the INFN "Survival" code — LEM I–III
#
# [batuff/Survival](https://github.com/batuff/Survival) (Manganaro et al. 2018,
# doi:10.1088/1361-6560/aab697) is the only other open-source LEM I–III
# implementation we know of, which makes it the one thing a paper cannot be:
# a second opinion. When pyRadBio disagrees with a published figure, comparing
# against Survival separates *our* bug from a reconstruction that two
# independent implementations both fail to match.
#
# Survival offers two fast approximations, and they differ in exactly the place
# pyRadBio had to patch:
#
# * **`rapidLEM_Scholz2006`** (GSI; Krämer & Scholz 2006) —
#   $\alpha_D = (1 - S_1)/d_\mathrm{LET}$.
# * **`rapidLEM_Russo2011`** (INFN) — the same, plus $\alpha_X(1 - d_\mathrm{in}/
#   d_\mathrm{LET})$: the track energy that lands *outside* the nucleus is
#   credited with the photon $\alpha$. That is precisely pyRadBio's own
#   photon-floor correction, arrived at independently.
#
# **Stopping power is not a free variable here.** `pyradbio.track.srim` reads
# Survival's own SRIM tables, defaulting to its two conventions (electronic
# stopping only; linear-in-energy interpolation), and reproduces its LET to
# ~3e-6. Any disagreement below is therefore a model difference, not a dE/dx one.
#
# **External data.** The reference curves are Survival output, generated by
# building and running the C++ code — they are not redistributed. Set
# `PYRADBIO_SURVIVAL_DIR` (JSON exports) and `PYRADBIO_SURVIVAL_SRC_DIR` (the
# source checkout, for the SRIM and η tables); the build/run recipe is in
# `docs/references/survival_repo_notes.md`. Without them this script prints what
# is missing and exits cleanly.
#
# **pyRadBio's own Monte Carlo (purple triangles) is read from a committed cache**,
# `validation/data/survival_our_mc.json`, so this script runs no Monte Carlo. The
# cache is regenerated by `scripts/lem_mc_vs_survival.py`, which documents the
# settings (per-point precision sizing, the near/far split that makes 300 MeV/u
# reachable); its `_provenance` header records the stopping power, engine and a
# numeric fingerprint that `tests/benchmark/test_survival_cache_fingerprint.py`
# recomputes. A point missing from the cache is skipped with a note. Quick mode
# (`PYRADBIO_QUICK=1`) draws every 6th reference energy, a 12-point fine grid in
# panel 5 and no two-track β.

