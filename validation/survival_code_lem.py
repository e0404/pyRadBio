# %% [markdown]
# ## 5. Survival's full Monte Carlo — the reference path
#
# The MC is what the approximations approximate: sample track positions, build
# S(D) at each imposed dose, LQ-fit for α and β. This panel is laid out like
# Manganaro et al. 2018 figure 5 — α and β against LET for HSG carbon, MC points
# with error bars against the analytic lines — because our grid *is* that
# figure's configuration (α_X = 0.313, β_X = 0.0615, R_N = 5 µm, D_t = 30 Gy).
#
# **β from the MC is a real measurement, not a failed one.** Its uncertainty
# grows with LET because the 1–6 Gy survival curve straightens out, and once the
# true β approaches zero the estimator scatters symmetrically *through* zero —
# so individual negative fits are the expected behaviour, not an error. Figure
# 5(b) of the paper shows exactly this: above ~200 keV/µm their points sit on
# zero with error bars crossing it. Plot β with its uncertainty and read it as a
# band, and it discriminates the β models; hide the negatives and it cannot.
#
# High LET is the *cheap* end of the MC — few traversals per cell at a fixed
# imposed dose, so carbon at 1 MeV/u costs ~10 min at 8000 cells where 300 MeV/u
# costs 6 h at 500. The open circles are a second pass at 16× the cells (σ_β
# ±0.003 rather than ±0.02); the filled ones are the 500-cell grid. Where they
# overlap, the coarse points sit ~1.5σ high with bars wide enough to hide it. That
# gap *is* the convergence story, so both are plotted. With the tight bars the β
# models separate unambiguously — see `docs/references/survival_repo_notes.md` §5.
#
# **Our own MC (purple triangles) runs to Survival's own MC energies** — carbon
# 300, protons 100 — for all three versions, so there is a pyRadBio point on every
# black marker; reaching them depends on the near/far split documented in
# `scripts/lem_mc_vs_survival.py` (carbon 300 has 9.7e6 traversals per cell at
# 6 Gy, of which only 2131 are ever resolved).

# %%
