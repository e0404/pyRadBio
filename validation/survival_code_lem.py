def _load(model: str, calculus: str) -> rt.SurvivalLQTable | None:
    """An optional export (the Monte-Carlo passes, the patched build), or None."""
    try:
        return rt.load_survival_table(m18.survival_table_filename(model, calculus))
    except (FileNotFoundError, OSError):
        return None


# Survival's reference MC. `MC` is the 500-cell grid over all three versions;
# `MC_HIP` is the 8000-cell LEM I carbon pass. Both are optional — the MC is
# expensive to generate and the panels degrade to lines-only without it.
MC = {m: _load(m, "MonteCarlo") for m in MODELS}
MC_HIP = {"LEMI": _load("LEMI", "MonteCarloHiP")}
# The paired sweep (`scripts/survival_paired_mc.py`): H/He/C/O at 3/10/30/100/300
# MeV/u for all three versions, each point's cell count sized to a target sigma on
# alpha; 57 of 60 points (median sigma_alpha 0.55%; LEM III helium and LEM II/III
# protons at 300 MeV/u are absent: one Survival cell there exceeds four hours).
#
# **These come from the UNPATCHED binary, so the LEM II/III squares carry
# Survival's own `logS_t2`/`logS_t3` defect** (section 6a of the notes) and sit
# systematically below our triangles. Measured MC-vs-MC over the 57 pairs, median
# |alpha ratio - 1| / median |z|: LEM I 0.66% / 1.01 (n=20), LEM II 2.73% / 3.53
# (n=19), LEM III 8.63% / 11.50 (n=18) -- tracking the *unpatched* analytic offsets
