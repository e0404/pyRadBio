"""SRIM ``<Ion>_Srim.dat`` stopping-power tables (the *Survival* code's LET source).

The INFN/UniTO "Survival" toolkit (Manganaro et al. 2018,
doi:10.1088/1361-6560/aab697; https://github.com/batuff/Survival) converts
between ion energy and LET with look-up tables generated by SRIM
(http://www.srim.org) and shipped in its ``data/`` folder as ``<symbol>_Srim.dat``
-- one file per ion, H through Ne.

This module reads those files so that a pyRadBio-vs-Survival comparison can be
run on **Survival's own LET**, removing stopping power as a free variable. That
matters more than it sounds: LEM alpha is a steep function of LET, so a few
percent of stopping-power disagreement is easily mistaken for a model-level
disagreement (the same reason [`load_trip_dedx`][pyradbio.benchmark.reference_tables.load_trip_dedx]
exists for TRiP98).

File format (fixed, 4 header lines then whitespace-separated rows):

```text
   Ion        dE/dx       dE/dx      Projected    Longitudinal   Lateral
  Energy      Elec.      Nuclear        Range      Straggling   Straggling
 (MeV/u)     (MeV/um)   (MeV/um)        (um)          (um)         (um)
----------- ----------- ----------- ------------- ------------  ---------
8.333e-04   5.641E-02   9.014E-02    0.0566        0.0209        0.0152
```

Two conventions must be reproduced exactly to match Survival:

1. **Electronic stopping only.** ``Survival::BetheBlochTable`` reads column 2
   and drops column 3; the line summing the two is commented out in
   ``src/usefulFunctions.cpp``. [`srim_stopping_power`][] therefore defaults
   to ``include_nuclear=False``. Nuclear stopping is negligible above ~1 MeV/u
   but reaches ~60% of the electronic term at the low-energy end of these
   tables, so the choice is not cosmetic there.
2. **Linear interpolation in energy.** ``BetheBlochTable::GetLET`` bisects for
   the bracketing pair and interpolates ``let`` linearly in ``e_c``. pyRadBio's
   default log-log interpolation is the better interpolant, so this module
   builds tables with ``interpolation="linear"`` to match the reference rather
   than to be right; see [`StoppingPowerTable`][].

The ``.dat`` files are **not** redistributed here (the Survival code is GPL-2;
pyRadBio is not). Point ``PYRADBIO_SURVIVAL_SRC_DIR`` at a Survival source
checkout -- the loader looks under its ``data/`` subfolder.

SRIM itself is a semi-empirical code; its heavy-ion water values differ from
ICRU/PSTAR at the few-percent level. Use these tables to reproduce *Survival*,
not as a modern stopping-power reference.
"""

from __future__ import annotations

from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import Literal

from pyradbio.core.elements import SYMBOL_TO_Z as ELEMENT_Z
from pyradbio.datasets import SURVIVAL_SRC, dataset_dir
from pyradbio.track.stopping_power import StoppingPowerTable, TabularStoppingPower

SRIM_IONS: tuple[str, ...] = ("H", "He", "Li", "Be", "B", "C", "N", "O", "F", "Ne")
"""Ions Survival ships a SRIM table for."""

SRIM_SUBDIR = "data"
"""Subfolder of a Survival checkout holding the ``.dat`` files."""

_HEADER_LINES = 4
_MEV_PER_UM_TO_KEV_PER_UM = 1.0e3


@dataclass(frozen=True, slots=True)
class SrimColumn:
    """One ion's SRIM table exactly as printed, in the file's own units."""

    symbol: str
    energy_MeV_u: tuple[float, ...]
    electronic_MeV_um: tuple[float, ...]
    nuclear_MeV_um: tuple[float, ...]
    projected_range_um: tuple[float, ...]
    longitudinal_straggling_um: tuple[float, ...]
    lateral_straggling_um: tuple[float, ...]

    @property
    def Z(self) -> int:
        """Atomic number of this ion."""
        return ELEMENT_Z[self.symbol]

    def let_keV_um(self, *, include_nuclear: bool = False) -> tuple[float, ...]:
        """Tabulated LET [keV/um]; electronic only unless ``include_nuclear``."""
        if include_nuclear:
            pairs = zip(self.electronic_MeV_um, self.nuclear_MeV_um, strict=True)
            return tuple((e + n) * _MEV_PER_UM_TO_KEV_PER_UM for e, n in pairs)
        return tuple(e * _MEV_PER_UM_TO_KEV_PER_UM for e in self.electronic_MeV_um)


def parse_srim_table(text: str, symbol: str) -> SrimColumn:
    """Parse the text of a ``<symbol>_Srim.dat`` file into a [`SrimColumn`][].

    Skips the four fixed header lines and reads six whitespace-separated
    columns per row. Blank lines are ignored; a row with fewer than six columns
    raises `ValueError` rather than being silently dropped.
    """
    rows = [line for line in text.splitlines()[_HEADER_LINES:] if line.strip()]
    if not rows:
        raise ValueError(f"{symbol}_Srim.dat contained no data rows")

    energy: list[float] = []
    electronic: list[float] = []
    nuclear: list[float] = []
    proj_range: list[float] = []
    longitudinal: list[float] = []
    lateral: list[float] = []
    for lineno, row in enumerate(rows, start=_HEADER_LINES + 1):
        cols = row.split()
        if len(cols) < 6:
            raise ValueError(
                f"{symbol}_Srim.dat line {lineno}: expected 6 columns, got {len(cols)}: {row!r}"
            )
        energy.append(float(cols[0]))
        electronic.append(float(cols[1]))
        nuclear.append(float(cols[2]))
        proj_range.append(float(cols[3]))
        longitudinal.append(float(cols[4]))
        lateral.append(float(cols[5]))

    return SrimColumn(
        symbol=symbol,
        energy_MeV_u=tuple(energy),
        electronic_MeV_um=tuple(electronic),
        nuclear_MeV_um=tuple(nuclear),
        projected_range_um=tuple(proj_range),
        longitudinal_straggling_um=tuple(longitudinal),
        lateral_straggling_um=tuple(lateral),
    )


def srim_data_dir(directory: str | Path | None = None) -> Path:
    """Directory holding the ``*_Srim.dat`` files.

    ``directory`` wins if given (and is used as-is); otherwise this resolves
    ``$PYRADBIO_SURVIVAL_SRC_DIR/data``, raising
    [`MissingDatasetError`][pyradbio.datasets.MissingDatasetError] when unconfigured.
    """
    if directory is not None:
        return Path(directory)
    return dataset_dir(SURVIVAL_SRC) / SRIM_SUBDIR


@lru_cache(maxsize=len(SRIM_IONS))
def load_srim_column(symbol: str, directory: str | Path | None = None) -> SrimColumn:
    """Load one ion's SRIM table by element symbol (e.g. ``"C"``)."""
    if symbol not in ELEMENT_Z:
        raise ValueError(f"unknown element symbol {symbol!r}")
    path = srim_data_dir(directory) / f"{symbol}_Srim.dat"
    if not path.is_file():
        raise FileNotFoundError(
            f"{path} not found. Point PYRADBIO_SURVIVAL_SRC_DIR at a Survival "
            "source checkout (its data/ folder holds the SRIM tables)."
        )
    return parse_srim_table(path.read_text(encoding="utf-8"), symbol)


def srim_stopping_power(
    symbols: Iterable[str] = SRIM_IONS,
    *,
    include_nuclear: bool = False,
    match_survival_interpolation: bool = True,
    directory: str | Path | None = None,
) -> TabularStoppingPower:
    """A [`StoppingPower`][pyradbio.track.stopping_power.StoppingPower] over the SRIM tables.

    Defaults reproduce ``Survival``'s LET exactly: electronic stopping only,
    linear-in-energy interpolation. Set ``include_nuclear=True`` or
    ``match_survival_interpolation=False`` to get the physically preferable
    variants instead (and then say so when quoting an agreement number).
    """
    interpolation: Literal["log-log", "linear"] = (
        "linear" if match_survival_interpolation else "log-log"
    )
    tables: dict[int, StoppingPowerTable] = {}
    for symbol in symbols:
        column = load_srim_column(symbol, directory)
        tables[column.Z] = StoppingPowerTable.from_arrays(
            column.energy_MeV_u,
            column.let_keV_um(include_nuclear=include_nuclear),
            interpolation,
        )
    if not tables:
        raise ValueError("no SRIM ions requested")
    return TabularStoppingPower(tables)


def srim_energy_range_MeV_u(symbols: Sequence[str] = SRIM_IONS) -> tuple[float, float]:
    """Energy range common to every requested SRIM table [MeV/u].

    The tables span roughly 8e-4 to 8e2 MeV/u but do not all start and end at
    exactly the same node, so a multi-ion sweep should clip to this.
    """
    columns = [load_srim_column(s) for s in symbols]
    return (
        max(c.energy_MeV_u[0] for c in columns),
        min(c.energy_MeV_u[-1] for c in columns),
    )
